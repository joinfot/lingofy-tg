def caption(key):
    c = CAP[key]
    tags = c["tags"]
    assert len(tags) <= 5, f"{key}: хештегов больше пяти"
    return "\n\n".join([c["body"], PDF[c["acc"]], " ".join(tags)])


def title(key):
    t = CAP[key]["title"]
    assert len(t) <= 100, f"{key}: заголовок длиннее 100 знаков"
    return t


