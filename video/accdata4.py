def _spread(rows):
    """Разносит правильный ответ по позициям.

    Писать варианты удобно, когда верный идёт первым, но смотреть такой
    квиз нельзя: к третьему вопросу видно, что ответ всегда сверху.
    Сдвиг фиксированный, чтобы пересборка давала тот же ролик.
    """
    shift = [1, 2, 0, 2]
    out = []
    for i, r in enumerate(rows):
        n = len(r[1])
        if n == 2:
            # «да/нет» уже написаны вперемешку: сдвиг бы их только выровнял
            out.append(r)
            continue
        s = shift[i % len(shift)] % n
        opts = [None] * n
        for j, o in enumerate(r[1]):
            opts[(j + s) % n] = o
        out.append((r[0], opts, (r[2] + s) % n) + tuple(r[3:]))
    return out


