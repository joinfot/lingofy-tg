def cfg(key):
    """Готовый конфиг ролика: содержание плюс оформление его аккаунта."""
    import acc as A
    v = dict(BY[key])
    th = dict(A.ACC[v["acc"]])
    th["fmt"] = v["fmt"]
    v.setdefault("foot", FOOT[v["acc"]])
    if "mus_off" in v:
        th["mus_off"] = v["mus_off"]
    v["th"] = th
    return v
