def _spread(rows):
    """Разводит верный ответ по позициям: иначе он всегда первый."""
    shift = [2, 0, 1, 0]
    out = []
    for n, r in enumerate(rows):
        q, opts, ok, why, de = r
        if len(opts) == 2:
            out.append(r)
            continue
        s = shift[n % len(shift)]
        order = opts[s:] + opts[:s]
        out.append((q, order, order.index(opts[ok]), why, de))
    return out


